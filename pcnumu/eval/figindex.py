"""Curated figure records for slides and the thesis.

A figure record is a PNG plus a sidecar markdown file with the same stable ID, kept in one flat folder
(default /data/nova/chow/pcnumu-runs/figures/):

    F-20261103-taper-tradeoff-fhc.png
    F-20261103-taper-tradeoff-fhc.md      <- frontmatter (fields below) + free-text caption

IDs are immutable: once a figure is shared, its ID always means that image. A corrected or restyled
version gets a new ID (suffix -v2) and the old sidecar gets `superseded_by`. This is what makes a
one-way rsync of the folder (no --delete) safe on every machine.

Frontmatter fields (one per line, `key: value`; lists as `[a, b]`):
    id, date (YYYY-MM-DD), machine, title, claim (one line), numbers, source (original path),
    script, commit, command, inputs, findings (vault entry heading), thesis (chapter/topic tag),
    slides (yes/no), status (candidate | thesis | superseded), superseded_by

Usage:
    python -I pcnumu/eval/figindex.py add --src <png> --id F-YYYYMMDD-slug [--field key=value ...]
    python -I pcnumu/eval/figindex.py index [--dir <figures dir>]   # writes INDEX.md
"""
import argparse
import datetime
import os
import shutil
import socket
import sys

DEFAULT_DIR = "/data/nova/chow/pcnumu-runs/figures"
FIELDS = ["id", "date", "machine", "title", "claim", "numbers", "source", "script", "commit", "command",
          "inputs", "findings", "thesis", "slides", "status", "superseded_by"]


def read_sidecar(path):
    meta, body, lines = {}, [], open(path).read().splitlines()
    if lines and lines[0] == "---":
        end = lines.index("---", 1)
        for ln in lines[1:end]:
            if ":" in ln:
                k, v = ln.split(":", 1)
                meta[k.strip()] = v.strip()
        body = lines[end + 1:]
    return meta, "\n".join(body).strip()


def write_sidecar(path, meta, body):
    out = ["---"] + [f"{k}: {meta.get(k, '')}" for k in FIELDS] + ["---", "", body.strip(), ""]
    open(path, "w").write("\n".join(out))


def cmd_add(a):
    if not a.id.startswith("F-") or not a.id[2:10].isdigit():
        sys.exit("id must look like F-YYYYMMDD-short-slug")
    png = os.path.join(a.dir, a.id + os.path.splitext(a.src)[1])
    side = os.path.join(a.dir, a.id + ".md")
    if os.path.exists(png) and not a.force:
        sys.exit(f"{png} exists; IDs are immutable, use a new ID (e.g. -v2) or --force before it is shared")
    os.makedirs(a.dir, exist_ok=True)
    shutil.copy2(a.src, png)
    meta = {"id": a.id, "date": f"{a.id[2:6]}-{a.id[6:8]}-{a.id[8:10]}", "machine": socket.gethostname().split(".")[0],
            "source": os.path.abspath(a.src), "status": "candidate", "slides": "yes"}
    body = ""
    if os.path.exists(side):
        old, body = read_sidecar(side)
        meta.update({k: v for k, v in old.items() if v})
    for kv in a.field or []:
        k, v = kv.split("=", 1)
        if k == "caption":
            body = v
        elif k in FIELDS:
            meta[k] = v
        else:
            sys.exit(f"unknown field {k}")
    write_sidecar(side, meta, body)
    print(side)


def cmd_index(a):
    recs = []
    for f in sorted(os.listdir(a.dir)):
        if f.startswith("F-") and f.endswith(".md"):
            meta, body = read_sidecar(os.path.join(a.dir, f))
            recs.append(meta)
    groups = {}
    for m in recs:
        groups.setdefault(m.get("thesis") or "untagged", []).append(m)
    out = [f"# Figure index ({len(recs)} figures)", "",
           f"Generated by `pcnumu/eval/figindex.py index` on {datetime.date.today()}. Edit the sidecars, not this file.", ""]
    for g in sorted(groups):
        out += [f"## {g}", "", "| ID | date | claim | status | findings |", "|---|---|---|---|---|"]
        for m in sorted(groups[g], key=lambda m: m.get("id", "")):
            st = m.get("status", "")
            if m.get("superseded_by"):
                st += f" → {m['superseded_by']}"
            out.append(f"| `{m.get('id')}` | {m.get('date', '')} | {m.get('claim', '')} | {st} | {m.get('findings', '')} |")
        out.append("")
    open(os.path.join(a.dir, "INDEX.md"), "w").write("\n".join(out))
    print(os.path.join(a.dir, "INDEX.md"))


def main():
    ap = argparse.ArgumentParser()
    sp = ap.add_subparsers(dest="cmd", required=True)
    p = sp.add_parser("add")
    p.add_argument("--src", required=True)
    p.add_argument("--id", required=True)
    p.add_argument("--field", action="append", help="key=value; key 'caption' sets the body text")
    p.add_argument("--force", action="store_true")
    p.add_argument("--dir", default=DEFAULT_DIR)
    p.set_defaults(fn=cmd_add)
    p = sp.add_parser("index")
    p.add_argument("--dir", default=DEFAULT_DIR)
    p.set_defaults(fn=cmd_index)
    a = ap.parse_args()
    a.fn(a)


if __name__ == "__main__":
    main()
